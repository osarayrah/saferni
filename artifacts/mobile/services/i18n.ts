export function translate(language: Language, value: string): string {
  return language === 'ar' ? ARABIC[value] ?? value : value;
}

export function useI18n(language: Language) {
  const t = useCallback((value: string) => translate(language, value), [language]);
  return { t, isArabic: language === 'ar', direction: language === 'ar' ? 'rtl' as const : 'ltr' as const };
}